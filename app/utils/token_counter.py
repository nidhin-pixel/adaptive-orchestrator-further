"""
Token counting utility for Adaptive LLM Orchestrator.

IMPORTANT NOTE ON BILLING & ACCURACY:
Pre-execution token counts generated by this module are estimates intended for:
- Routing decisions (matching context window limits)
- Heuristic budget guardrails before sending API calls
- Offline simulation

Provider-reported token counts returned in `ExecutionResult.prompt_tokens` and
`ExecutionResult.completion_tokens` are the authoritative ground truth for billing
and analytics accounting.
"""

from __future__ import annotations

import math
import re
from typing import Any, Optional, Tuple

try:
    import tiktoken  # type: ignore
    _TIKTOKEN_AVAILABLE = True
except ImportError:
    tiktoken = None  # type: ignore
    _TIKTOKEN_AVAILABLE = False


def is_tiktoken_available() -> bool:
    """Check whether tiktoken library is available in the current environment."""
    return _TIKTOKEN_AVAILABLE


def estimate_fallback_tokens(text: str) -> int:
    """
    Documented fallback token estimator when tiktoken or specific model tokenizer is unavailable.

    Heuristic Rule:
    In standard English text and code, 1 token roughly corresponds to 4 characters
    or ~0.75 words (approx. 1.33 tokens per whitespace-separated word).
    To provide a resilient, conservative estimate across varied inputs:
    - Empty or non-string text evaluates to 0.
    - Non-empty text computes ceil(len(text) / 4.0).
    - If word-based heuristic (words * 1.33) yields a higher estimate (e.g. for long whitespace-separated tokens),
      we take the balanced average to prevent massive undercounting or overcounting.

    Args:
        text: Input string to estimate.

    Returns:
        int: Estimated token count (minimum 1 for non-empty text).
    """
    if not text or not isinstance(text, str):
        return 0

    stripped = text.strip()
    if not stripped:
        return 0

    char_based = math.ceil(len(stripped) / 4.0)
    words = re.findall(r"\S+", stripped)
    word_based = math.ceil(len(words) * 1.33)

    # Use the max of char-based and word-based heuristics, with a lower bound of 1
    return max(1, max(char_based, word_based))


def count_tokens(text: Optional[str], model_name: str = "gpt-4o") -> int:
    """
    Count tokens for a given text string.
    Uses tiktoken BPE tokenizer when available; cleanly falls back to documented heuristic
    if tiktoken is unavailable, if an unsupported model is passed, or if tokenization fails.

    Args:
        text: Input text (prompt or completion). Returns 0 for None, empty, or invalid types.
        model_name: Model identifier used to resolve the tokenizer encoding.

    Returns:
        int: Total token count.
    """
    if text is None or not isinstance(text, str):
        return 0

    if not text.strip():
        return 0

    if _TIKTOKEN_AVAILABLE and tiktoken is not None:
        try:
            try:
                encoding = tiktoken.encoding_for_model(model_name)
            except KeyError:
                # Default to cl100k_base or o200k_base if model name is not explicitly in tiktoken's registry
                if "gpt-4o" in model_name or "o1" in model_name:
                    encoding = tiktoken.get_encoding("o200k_base")
                else:
                    encoding = tiktoken.get_encoding("cl100k_base")

            return len(encoding.encode(text))
        except Exception:
            # Fall back to heuristic if encoding crashes or unexpected error occurs
            return estimate_fallback_tokens(text)

    return estimate_fallback_tokens(text)


def count_prompt_and_completion_tokens(
    prompt: Optional[str],
    completion: Optional[str],
    model_name: str = "gpt-4o",
) -> Tuple[int, int]:
    """
    Count tokens for both prompt and completion strings.

    Args:
        prompt: User or system prompt text.
        completion: Generated completion text.
        model_name: Model identifier for tokenizer lookup.

    Returns:
        Tuple[int, int]: (prompt_tokens, completion_tokens)
    """
    prompt_count = count_tokens(prompt, model_name=model_name)
    completion_count = count_tokens(completion, model_name=model_name)
    return prompt_count, completion_count
